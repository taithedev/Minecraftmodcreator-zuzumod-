import fs from 'node:fs';
import fsp from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { PNG } from 'pngjs';
import AdmZip from 'adm-zip';

export const workspace = path.resolve(process.env.ZUZUMOD_WORKSPACE || path.join(os.homedir(), 'ZuzuModStudio', 'projects'));
export const idPattern = /^[a-z][a-z0-9_]{1,48}$/;
const templateUrl = 'https://codeload.github.com/NeoForgeMDKs/MDK-1.21.1-ModDevGradle/zip/refs/heads/main';
export const ensureWorkspace = () => fsp.mkdir(workspace, { recursive: true });
export const safeId = id => {
  if (typeof id !== 'string' || !idPattern.test(id)) throw new Error('Mod ID must be 2–49 lowercase letters, numbers or underscores, beginning with a letter.');
  return id;
};
export function projectDir(id) { return path.join(workspace, safeId(id)); }
export function withinProject(id, relative) {
  if (typeof relative !== 'string' || !relative || relative.includes('\0') || path.isAbsolute(relative)) throw new Error('Invalid project path.');
  const base = projectDir(id);
  const resolved = path.resolve(base, relative);
  if (!resolved.startsWith(base + path.sep)) throw new Error('Path must stay inside the project.');
  return resolved;
}
export async function listProjects() {
  await ensureWorkspace();
  const entries = await fsp.readdir(workspace, { withFileTypes: true });
  const projects = await Promise.all(entries.filter(e => e.isDirectory() && idPattern.test(e.name)).map(async e => {
    try { return JSON.parse(await fsp.readFile(path.join(workspace, e.name, '.zuzumod', 'project.json'), 'utf8')); }
    catch { return null; }
  }));
  return projects.filter(Boolean).sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}
export async function readMeta(id) { return JSON.parse(await fsp.readFile(withinProject(id, '.zuzumod/project.json'), 'utf8')); }
export async function readElements(id) { return JSON.parse(await fsp.readFile(withinProject(id, '.zuzumod/elements.json'), 'utf8')); }
const toClass = value => value.split('_').map(p => p[0].toUpperCase() + p.slice(1)).join('');
const toConstant = value => value.toUpperCase();
const writeJSON = (dest, data) => fsp.mkdir(path.dirname(dest), { recursive: true }).then(() => fsp.writeFile(dest, JSON.stringify(data, null, 2) + '\n'));
const validHex = color => /^#[0-9a-f]{6}$/i.test(color || '') ? color : '#8b5cf6';

async function generateStarter(id) {
  const meta = await readMeta(id);
  const entries = await readElements(id);
  const className = toClass(id) + 'Mod';
  const pkg = 'dev.zuzumod.' + id;
  const javaDir = withinProject(id, 'src/main/java/' + pkg.replaceAll('.', '/'));
  await fsp.mkdir(javaDir, { recursive: true });
  const constants = [];
  const regs = [
    'public static final DeferredRegister.Items ITEMS = DeferredRegister.createItems("' + id + '");',
    'public static final DeferredRegister.Blocks BLOCKS = DeferredRegister.createBlocks("' + id + '");'
  ];
  for (const e of entries) {
    const c = toConstant(e.id);
    if (e.type === 'block') {
      regs.push('public static final DeferredBlock<Block> ' + c + ' = BLOCKS.registerSimpleBlock("' + e.id + '", BlockBehaviour.Properties.of().strength(2.0f));');
      regs.push('public static final DeferredItem<BlockItem> ' + c + '_ITEM = ITEMS.registerSimpleBlockItem("' + e.id + '", ' + c + ');');
      constants.push('if (event.getTabKey() == CreativeModeTabs.BUILDING_BLOCKS) event.accept(GeneratedContent.' + c + '_ITEM);');
    } else {
      regs.push('public static final DeferredItem<Item> ' + c + ' = ITEMS.registerSimpleItem("' + e.id + '", new Item.Properties());');
      constants.push('if (event.getTabKey() == CreativeModeTabs.INGREDIENTS) event.accept(GeneratedContent.' + c + ');');
    }
  }
  const registry = [
    'package ' + pkg + ';', '',
    'import net.minecraft.world.item.Item;',
    'import net.minecraft.world.item.BlockItem;',
    'import net.minecraft.world.level.block.Block;',
    'import net.minecraft.world.level.block.state.BlockBehaviour;',
    'import net.neoforged.bus.api.IEventBus;',
    'import net.neoforged.neoforge.registries.DeferredRegister;',
    'import net.neoforged.neoforge.registries.DeferredItem;',
    'import net.neoforged.neoforge.registries.DeferredBlock;',
    '',
    '/** Generated by ZuzuMod Studio. Edit in the Code view if desired. */',
    'public final class GeneratedContent {',
    ...regs.map(r => '    ' + r),
    '    private GeneratedContent() {}',
    '    public static void register(IEventBus bus) { BLOCKS.register(bus); ITEMS.register(bus); }',
    '}', ''
  ].join('\n');
  const main = [
    'package ' + pkg + ';', '',
    'import net.neoforged.fml.common.Mod;',
    'import net.neoforged.bus.api.IEventBus;',
    'import net.neoforged.neoforge.event.BuildCreativeModeTabContentsEvent;',
    'import net.minecraft.world.item.CreativeModeTabs;', '',
    '@Mod("' + id + '")',
    'public class ' + className + ' {',
    '    public ' + className + '(IEventBus bus) {',
    '        GeneratedContent.register(bus);',
    '        bus.addListener(this::addToCreative);',
    '    }',
    '    private void addToCreative(BuildCreativeModeTabContentsEvent event) {',
    ...constants.map(c => '        ' + c),
    '    }',
    '}', ''
  ].join('\n');
  await Promise.all([
    fsp.writeFile(path.join(javaDir, 'GeneratedContent.java'), registry),
    fsp.writeFile(path.join(javaDir, className + '.java'), main)
  ]);
  const lang = {};
  for (const e of entries) {
    lang[(e.type === 'block' ? 'block.' : 'item.') + id + '.' + e.id] = e.name;
    const assetDir = 'src/main/resources/assets/' + id + '/';
    if (e.type === 'block') {
      await writeJSON(withinProject(id, assetDir + 'blockstates/' + e.id + '.json'), { variants: { '': { model: id + ':block/' + e.id } } });
      await writeJSON(withinProject(id, assetDir + 'models/block/' + e.id + '.json'), { parent: 'minecraft:block/cube_all', textures: { all: id + ':block/' + e.id } });
      await writeJSON(withinProject(id, assetDir + 'models/item/' + e.id + '.json'), { parent: id + ':block/' + e.id });
    } else {
      await writeJSON(withinProject(id, assetDir + 'models/item/' + e.id + '.json'), { parent: 'minecraft:item/generated', textures: { layer0: id + ':item/' + e.id } });
    }
  }
  await writeJSON(withinProject(id, 'src/main/resources/assets/' + id + '/lang/en_us.json'), lang);
}

async function fetchTemplate() {
  const response = await fetch(templateUrl, { signal: AbortSignal.timeout(45000), headers: { 'User-Agent': 'ZuzuModStudio/0.1' } });
  if (!response.ok) throw new Error('Could not download official NeoForge starter (HTTP ' + response.status + ').');
  const size = Number(response.headers.get('content-length') || 0);
  if (size > 35_000_000) throw new Error('Starter archive too large.');
  const data = Buffer.from(await response.arrayBuffer());
  if (data.length > 35_000_000) throw new Error('Starter archive too large.');
  return new AdmZip(data);
}

export async function createProject({ name, id }) {
  id = safeId(String(id || '').toLowerCase());
  name = String(name || '').trim().slice(0, 64);
  if (!name) throw new Error('Enter a project name.');
  await ensureWorkspace();
  const destination = projectDir(id);
  if (fs.existsSync(destination)) throw new Error('A project with that ID already exists.');
  const zip = await fetchTemplate();
  const temp = await fsp.mkdtemp(path.join(workspace, '.creating-'));
  try {
    const entries = zip.getEntries();
    if (entries.length > 1800) throw new Error('Unexpected starter archive.');
    for (const entry of entries) {
      if (entry.isDirectory) continue;
      const relative = entry.entryName.split('/').slice(1).join('/');
      if (!relative || relative.includes('..') || path.posix.isAbsolute(relative)) continue;
      if (relative.startsWith('src/main/java/') || relative.startsWith('src/main/resources/assets/') || relative.startsWith('src/main/resources/data/')) continue;
      if (relative.startsWith('.github/')) continue;
      const target = path.resolve(temp, relative);
      if (!target.startsWith(temp + path.sep)) continue;
      await fsp.mkdir(path.dirname(target), { recursive: true });
      await fsp.writeFile(target, entry.getData());
    }
    const properties = path.join(temp, 'gradle.properties');
    let data = await fsp.readFile(properties, 'utf8');
    const replacements = { mod_id: id, mod_name: name, mod_group_id: 'dev.zuzumod.' + id };
    for (const [key, value] of Object.entries(replacements)) data = data.replace(new RegExp('^' + key + '=.*$', 'm'), key + '=' + value);
    await fsp.writeFile(properties, data);
    await writeJSON(path.join(temp, '.zuzumod', 'project.json'), { id, name, loader: 'NeoForge', minecraft: '1.21.1', version: '1.0.0', createdAt: new Date().toISOString() });
    await writeJSON(path.join(temp, '.zuzumod', 'elements.json'), []);
    await fsp.rename(temp, destination);
    await generateStarter(id);
    return readMeta(id);
  } catch (error) {
    await fsp.rm(temp, { recursive: true, force: true });
    if (fs.existsSync(destination)) await fsp.rm(destination, { recursive: true, force: true });
    throw error;
  }
}

async function generateTexture(target, color, type) {
  if (fs.existsSync(target)) return;
  const png = new PNG({ width: 16, height: 16 });
  const hex = validHex(color).slice(1);
  const rgb = [0, 2, 4].map(i => parseInt(hex.slice(i, i + 2), 16));
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
    const offset = (y * 16 + x) * 4;
    const lighter = ((x + y) % 4 === 0 ? 24 : 0) + (type === 'block' && (x === 0 || y === 0) ? -25 : 0);
    for (let k = 0; k < 3; k++) png.data[offset + k] = Math.max(0, Math.min(255, rgb[k] + lighter));
    png.data[offset + 3] = type === 'item' && (x < 2 || y < 2 || x > 13 || y > 13) ? 0 : 255;
  }
  await fsp.mkdir(path.dirname(target), { recursive: true });
  await fsp.writeFile(target, PNG.sync.write(png));
}

export async function addElement(id, input) {
  const type = input.type;
  const elementId = String(input.id || '').toLowerCase();
  const name = String(input.name || '').trim().slice(0, 60);
  if (!['item', 'block'].includes(type)) throw new Error('Choose an item or block.');
  safeId(elementId);
  if (!name) throw new Error('Element name is required.');
  const elements = await readElements(id);
  if (elements.length >= 128) throw new Error('This project reached the 128-element UI limit.');
  if (elements.some(e => e.id === elementId)) throw new Error('That element ID is already in use.');
  const color = validHex(input.color);
  const entry = { id: elementId, name, type, color };
  elements.push(entry);
  await writeJSON(withinProject(id, '.zuzumod/elements.json'), elements);
  await generateStarter(id);
  await generateTexture(withinProject(id, 'src/main/resources/assets/' + id + '/textures/' + type + '/' + elementId + '.png'), color, type);
  return entry;
}

export async function projectFiles(id) {
  const root = projectDir(id);
  const result = [];
  async function walk(folder, relative = '') {
    if (result.length >= 500) return;
    for (const entry of await fsp.readdir(folder, { withFileTypes: true })) {
      if (['.gradle', 'build', 'run', 'runs', '.git'].includes(entry.name)) continue;
      const child = relative ? relative + '/' + entry.name : entry.name;
      if (entry.isDirectory()) await walk(path.join(folder, entry.name), child);
      else if (/\.(java|json|toml|gradle|properties|md|txt|cfg|yml|yaml|bat)$/i.test(entry.name) || entry.name === 'gradlew') result.push(child);
    }
  }
  await walk(root);
  return result.sort();
}

export async function readCodeFile(id, relative) {
  if (!/\.(java|json|toml|gradle|properties|md|txt|cfg|yml|yaml|bat)$/i.test(relative) && relative !== 'gradlew') throw new Error('Not an editable text file.');
  const target = withinProject(id, relative);
  const stats = await fsp.lstat(target);
  if (!stats.isFile() || stats.size > 400_000) throw new Error('File too large or unavailable.');
  return fsp.readFile(target, 'utf8');
}

export async function writeCodeFile(id, relative, content) {
  if (typeof content !== 'string' || content.length > 400_000) throw new Error('Invalid file content.');
  if (!/\.(java|json|toml|gradle|properties|md|txt|cfg|yml|yaml|bat)$/i.test(relative)) throw new Error('Unsupported file type.');
  const target = withinProject(id, relative);
  await fsp.mkdir(path.dirname(target), { recursive: true });
  if (fs.existsSync(target) && !(await fsp.lstat(target)).isFile()) throw new Error('Cannot replace this file.');
  await fsp.writeFile(target, content, 'utf8');
}
export function textureRelative(id, type, elementId) {
  safeId(id); safeId(elementId);
  if (!['item', 'block'].includes(type)) throw new Error('Invalid asset type.');
  return 'src/main/resources/assets/' + id + '/textures/' + type + '/' + elementId + '.png';
}
export async function saveTexture(id, type, elementId, dataUrl) {
  const elements = await readElements(id);
  if (!elements.some(e => e.id === elementId && e.type === type)) throw new Error('Element not found.');
  if (typeof dataUrl !== 'string' || !/^data:image\/png;base64,[A-Za-z0-9+/=]+$/.test(dataUrl)) throw new Error('Expected PNG image data.');
  const bytes = Buffer.from(dataUrl.split(',')[1], 'base64');
  if (bytes.length > 500000) throw new Error('Texture too large.');
  const image = PNG.sync.read(bytes);
  if (image.width !== 16 || image.height !== 16) throw new Error('Textures must be 16×16 pixels.');
  await fsp.writeFile(withinProject(id, textureRelative(id, type, elementId)), bytes);
}
export async function listArtifacts(id) {
  const folder = withinProject(id, 'build/libs');
  try {
    const entries = await fsp.readdir(folder, { withFileTypes: true });
    return entries.filter(x => x.isFile() && x.name.endsWith('.jar') && !x.name.endsWith('-sources.jar')).map(x => x.name);
  } catch { return []; }
}
